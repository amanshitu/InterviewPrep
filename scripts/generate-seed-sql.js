// One-time generator: reads public/questions.js (the static question bank
// this app shipped with before the relational redesign) and emits a SQL
// file that seeds it into D1 as the official, pre-approved question_sets/
// questions rows. Run with `node scripts/generate-seed-sql.js`, then apply
// the output with `wrangler d1 execute ... --file=./migrations/seed_official_bank.sql`.
//
// Question ids are kept identical to the ids already used in questions.js
// (e.g. "hr1-01") so the backfill script can match a user's existing
// shownIds/questionStats directly, with no id-remapping step.
"use strict";
const fs = require("fs");
const path = require("path");

const srcPath = path.join(__dirname, "..", "public", "questions.js");
const outPath = path.join(__dirname, "..", "migrations", "seed_official_bank.sql");

const src = fs.readFileSync(srcPath, "utf8");
const jsonStr = src.replace("window.QUESTION_BANK = ", "").replace(/;\s*$/, "");
const bank = JSON.parse(jsonStr);

function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

const now = new Date().toISOString();
const lines = [];
lines.push("-- Generated by scripts/generate-seed-sql.js from public/questions.js. Do not hand-edit.");
lines.push("-- One question_sets row per curriculum group; questions keep their original ids.");
lines.push("");

bank.groups.forEach((g) => {
  lines.push(
    `INSERT INTO question_sets (id, owner_user_id, title, track, visibility, created_at, approved_at, approved_by) VALUES (${sqlStr(g.id)}, NULL, ${sqlStr(g.label)}, ${sqlStr(g.id)}, 'shared', ${sqlStr(now)}, ${sqlStr(now)}, NULL);`,
  );
});
lines.push("");

bank.topics.forEach((topic, topicOrder) => {
  const setId = topic.group;
  topic.questions.forEach((q, sortOrder) => {
    lines.push(
      `INSERT INTO questions (id, set_id, topic_label, topic_order, sort_order, q, a, created_at) VALUES (${sqlStr(q.id)}, ${sqlStr(setId)}, ${sqlStr(topic.title)}, ${topicOrder}, ${sortOrder}, ${sqlStr(q.q)}, ${sqlStr(q.a)}, ${sqlStr(now)});`,
    );
  });
});

fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${lines.length} statements to ${outPath}`);
console.log(`Sets: ${bank.groups.length}, questions: ${bank.topics.reduce((n, t) => n + t.questions.length, 0)}`);
