// One-time backfill: converts every existing user_state JSON blob into the
// new relational tables (user_question_progress, users.streak_*), and makes
// sure every existing user is subscribed to the official question sets
// (accounts created before this migration never got that auto-subscribe
// step that now runs at signup).
//
// Usage:
//   wrangler d1 execute interview-prep-db --<local|remote> --command \
//     "SELECT user_id, state_json FROM user_state" --json > dump.json
//   node scripts/generate-backfill-sql.js dump.json > migrations/backfill.sql
//   wrangler d1 execute interview-prep-db --<local|remote> --file=./migrations/backfill.sql
"use strict";
const fs = require("fs");

const dumpPath = process.argv[2];
if (!dumpPath) {
  console.error("Usage: node generate-backfill-sql.js <user_state_dump.json>");
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(dumpPath, "utf8"));
const rows = (raw[0] && raw[0].results) || [];

function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

const now = new Date().toISOString();
const lines = [];
lines.push("-- Generated by scripts/generate-backfill-sql.js. Do not hand-edit.");
lines.push("");

// Every existing user gets subscribed to every official (system) set,
// exactly like signup now does automatically — idempotent.
lines.push(
  `INSERT INTO user_question_sets (user_id, set_id, subscribed_at)
   SELECT u.id, qs.id, ${sqlStr(now)}
   FROM users u, question_sets qs
   WHERE qs.owner_user_id IS NULL
     AND NOT EXISTS (SELECT 1 FROM user_question_sets WHERE user_id = u.id AND set_id = qs.id);`,
);
lines.push("");

rows.forEach((row) => {
  let state;
  try {
    state = JSON.parse(row.state_json);
  } catch {
    return;
  }
  const userId = row.user_id;

  const streak = state.streak || {};
  lines.push(
    `UPDATE users SET streak_count = ${streak.count || 0}, streak_longest = ${streak.longest || 0}, streak_last_active = ${streak.lastActiveDate ? sqlStr(streak.lastActiveDate) : "NULL"} WHERE id = ${sqlStr(userId)};`,
  );

  const topics = state.topics || {};
  const questionStats = state.questionStats || {};
  Object.keys(topics).forEach((topicId) => {
    const t = topics[topicId];
    const status = t.status === "done" ? "done" : t.status === "in_progress" ? "shown" : null;
    if (!status) return;
    (t.shownIds || []).forEach((qid) => {
      const stat = questionStats[qid] || {};
      lines.push(
        `INSERT INTO user_question_progress (user_id, question_id, status, first_shown_at, last_shown_at, last_result, times_shown, correct_streak)
         VALUES (${sqlStr(userId)}, ${sqlStr(qid)}, ${sqlStr(status)}, ${sqlStr(t.startedAt || now)}, ${sqlStr(stat.lastShown || t.startedAt || now)}, ${stat.lastResult ? sqlStr(stat.lastResult) : "NULL"}, ${stat.timesShown || 0}, ${stat.correctStreak || 0})
         ON CONFLICT(user_id, question_id) DO NOTHING;`,
      );
    });
    if (t.status === "done") {
      lines.push(
        `INSERT INTO activity_log (user_id, occurred_at, event_type, topic_id, question_id, result) VALUES (${sqlStr(userId)}, ${sqlStr(t.doneAt || now)}, 'topic_completed_legacy', ${sqlStr(topicId)}, NULL, NULL);`,
      );
    }
  });
});

const out = lines.join("\n") + "\n";
process.stdout.write(out);
console.error(`Generated ${lines.length} statements for ${rows.length} user_state row(s).`);
